def data_processing(Review):
    if not isinstance(Review, str):
        Review = str(Review)

    Review = Review.lower()
    Review = re.sub(r"https\S+|www\S+https\S+", '', Review, flags=re.MULTILINE)
    Review = re.sub(r'/@w+|#','', Review)
    Review = re.sub(r'[^a-zA-Z0-9 ]','', Review) # More robust regex to keep alphanumeric characters and spaces
    Review_tokens = word_tokenize(Review)
    filtered_Review = [w for w in Review_tokens if not w in stop_words]
    return " ".join(filtered_Review)


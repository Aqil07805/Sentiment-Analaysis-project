# Function to get top n-grams for a given sentiment
def get_top_ngrams(df, sentiment_type, n=10, ngram_range=(2,2)):
    sentiment_df = df[df['sentiment'] == sentiment_type]
    # Ensure 'Translated' column is treated as strings and handle NaNs
    text = ' '.join(sentiment_df['Translated'].astype(str).tolist())

    # Use CountVectorizer to find n-grams
    vectorizer = CountVectorizer(ngram_range=ngram_range, stop_words='english')
    X = vectorizer.fit_transform([text])

    # Get feature names (n-grams) and their counts
    feature_names = vectorizer.get_feature_names_out()
    counts = X.sum(axis=0).A1

    # Create a DataFrame for easy sorting
    ngram_counts = pd.DataFrame({'ngram': feature_names, 'count': counts})
    top_ngrams = ngram_counts.sort_values(by='count', ascending=False).head(n)
    return top_ngrams

